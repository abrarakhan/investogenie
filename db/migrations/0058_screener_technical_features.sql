create table if not exists public.screener_technical_daily (
  asset_id uuid not null references public.assets(id) on delete cascade,
  date date not null,
  close numeric(20,6),
  sma_20 numeric(20,6), sma_50 numeric(20,6), sma_100 numeric(20,6),
  sma_150 numeric(20,6), sma_200 numeric(20,6),
  ema_20 numeric(20,6), ema_50 numeric(20,6),
  distance_sma_20_pct numeric(12,4), distance_sma_50_pct numeric(12,4),
  distance_sma_100_pct numeric(12,4), distance_sma_150_pct numeric(12,4), distance_sma_200_pct numeric(12,4),
  distance_ema_20_pct numeric(12,4), distance_ema_50_pct numeric(12,4),
  sma_20_vs_50_pct numeric(12,4), sma_20_vs_100_pct numeric(12,4), sma_20_vs_150_pct numeric(12,4),
  sma_20_vs_200_pct numeric(12,4), sma_50_vs_100_pct numeric(12,4), sma_50_vs_150_pct numeric(12,4),
  sma_50_vs_200_pct numeric(12,4), sma_100_vs_150_pct numeric(12,4), sma_100_vs_200_pct numeric(12,4),
  sma_150_vs_200_pct numeric(12,4), rsi_14 numeric(12,4), atr_pct_14 numeric(12,4),
  volume_ratio_20 numeric(12,4), return_5d numeric(12,4), return_20d numeric(12,4),
  return_63d numeric(12,4), forward_return_5d numeric(12,4),
  forward_return_20d numeric(12,4), forward_return_60d numeric(12,4),
  feature_version text not null default 'technical_v1',
  computed_at timestamptz not null default now(),
  primary key(asset_id,date)
);
create index if not exists screener_technical_daily_date_idx
  on public.screener_technical_daily(date desc);

